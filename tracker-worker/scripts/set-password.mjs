/* Sets (or resets) a password for an account that already exists in D1.

     node scripts/set-password.mjs you@example.com "a long password"
     npx wrangler d1 execute git-challenge-tracker --remote --file=./set-password.sql

   Uses the same PBKDF2-SHA256 record format the Worker verifies against, so
   whatever iteration count you hash with here keeps working even if the
   Worker's PBKDF2_ITERATIONS var changes later.
*/

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { webcrypto as crypto } from 'node:crypto';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '..', 'set-password.sql');

const [email, password, iterationsArg] = process.argv.slice(2);

if (!email || !password) {
  console.error('usage: node scripts/set-password.mjs <email> <password> [iterations]');
  process.exit(1);
}
if (password.length < 8) {
  console.error('password must be at least 8 characters');
  process.exit(1);
}

// Keep this in step with PBKDF2_ITERATIONS in wrangler.jsonc: the login that
// checks this hash has to fit the plan's CPU budget (10ms per request on the
// Workers Free plan). 25000 rounds is roughly 4ms.
const iterations = Number(iterationsArg) || 25000;

const toHex = (bytes) => [...bytes].map((b) => b.toString(16).padStart(2, '0')).join('');

const salt = crypto.getRandomValues(new Uint8Array(16));
const key = await crypto.subtle.importKey('raw', new TextEncoder().encode(password), 'PBKDF2', false, ['deriveBits']);
const bits = await crypto.subtle.deriveBits({ name: 'PBKDF2', hash: 'SHA-256', salt, iterations }, key, 256);

const record = `pbkdf2-sha256$${iterations}$${toHex(salt)}$${toHex(new Uint8Array(bits))}`;
const quote = (value) => `'${String(value).replace(/'/g, "''")}'`;

const sql = `-- GENERATED by scripts/set-password.mjs for ${email}
UPDATE users SET password = ${quote(record)} WHERE email = ${quote(email.trim().toLowerCase())};
`;

fs.writeFileSync(OUT, sql);

console.log(`  password record written for ${email} (${iterations} iterations)`);
console.log('');
console.log('  next:');
console.log('    npx wrangler d1 execute git-challenge-tracker --remote --file=./set-password.sql');
console.log('');
console.log('  delete set-password.sql once it has run - it is a live credential.');
